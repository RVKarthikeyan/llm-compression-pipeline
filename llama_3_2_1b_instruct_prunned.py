from transformers import AutoTokenizer, AutoModelForCausalLM
from datasets import load_dataset

def load_and_prepare_dataset(tokenizer, max_length=512):
    """Load and prepare the guanaco dataset for instruction tuning"""
    print("Loading dataset...")

    dataset = load_dataset(
        CONFIG["dataset"],
        split=CONFIG["dataset_split"]
    )

    print(f"Loaded {len(dataset)} examples")

    def format_prompt(example):
        """Format using Llama-3 chat template"""
        text = example["text"]
        return {"text": text}

    def tokenize_function(examples):
        """Tokenize the examples"""
        outputs = tokenizer(
            examples["text"],
            truncation=True,
            max_length=max_length,
            padding="max_length",
            return_tensors=None,
        )
        outputs["labels"] = outputs["input_ids"].copy()
        return outputs

    # Format dataset
    dataset = dataset.map(format_prompt, remove_columns=dataset.column_names)

    # Tokenize
    tokenized_dataset = dataset.map(
        tokenize_function,
        batched=True,
        remove_columns=dataset.column_names,
        desc="Tokenizing dataset"
    )

    return tokenized_dataset


def test_model(model, tokenizer, prompt="Hello, how are you?", max_new_tokens=100):
    """Test the model with a simple prompt using Llama-3 chat format"""
    # Format prompt using Llama-3 instruct template
    messages = [{"role": "user", "content": prompt}]
    if hasattr(tokenizer, "apply_chat_template"):
        formatted = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True
        )
    else:
        formatted = f"<|begin_of_text|><|start_header_id|>user<|end_header_id|>\n\n{prompt}<|eot_id|><|start_header_id|>assistant<|end_header_id|>\n\n"

    inputs = tokenizer(formatted, return_tensors="pt").to(model.device)

    print(f"\nPrompt: {prompt}")
    print("Generating response...")

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            temperature=0.7,
            do_sample=True,
            top_p=0.9,
            pad_token_id=tokenizer.eos_token_id,
        )

    # Decode only the new tokens (not the prompt)
    new_tokens = outputs[0][inputs["input_ids"].shape[1]:]
    response = tokenizer.decode(new_tokens, skip_special_tokens=True)
    print(f"Response: {response}")
    print("-" * 50)

    return response

