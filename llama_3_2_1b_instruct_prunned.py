"""## Step 3: Define Layer Collapse Class"""

import torch
import torch.nn as nn
from typing import List, Tuple

class LayerCollapser:
    """Implements LaCo (Layer Collapse) technique for model pruning"""

    def __init__(self, model, tokenizer):
        self.model = model
        self.tokenizer = tokenizer
        self.device = next(model.parameters()).device

    def get_layers(self):
        """Get the transformer layers from the model"""
        if hasattr(self.model, 'model'):
            if hasattr(self.model.model, 'layers'):
                return self.model.model.layers
        raise AttributeError("Could not find model layers")

    def merge_two_layers(self, layer1, layer2):
        """
        Merge two adjacent layers by averaging their weights
        Handles: Attention projections, MLP gates, and LayerNorms
        """
        print(f"  Merging layers by averaging weights...")

        state_dict1 = layer1.state_dict()
        state_dict2 = layer2.state_dict()

        merged_state_dict = {}
        for key in state_dict1.keys():
            if key in state_dict2:
                merged_state_dict[key] = (state_dict1[key] + state_dict2[key]) / 2.0
            else:
                merged_state_dict[key] = state_dict1[key]

        layer1.load_state_dict(merged_state_dict)
        return layer1

    def collapse_layers(self, layers_to_merge: List[Tuple[int, int]]):
        """
        Collapse specified layer pairs
        Args:
            layers_to_merge: List of tuples (layer_idx1, layer_idx2) to merge
        """
        layers = self.get_layers()
        original_num_layers = len(layers)

        print(f"Original model has {original_num_layers} layers")
        print(f"Will merge {len(layers_to_merge)} layer pairs: {layers_to_merge}")

        # Sort in reverse order to avoid index shifting issues
        layers_to_merge_sorted = sorted(layers_to_merge, reverse=True)
        layers_list = list(layers)

        for idx1, idx2 in layers_to_merge_sorted:
            if idx2 >= len(layers_list) or idx1 >= len(layers_list):
                print(f"Warning: Cannot merge layers {idx1} and {idx2}, out of range")
                continue

            if idx2 != idx1 + 1:
                print(f"Warning: Layers {idx1} and {idx2} are not adjacent")

            print(f"Merging layer {idx1} and {idx2}...")
            merged_layer = self.merge_two_layers(layers_list[idx1], layers_list[idx2])
            layers_list[idx1] = merged_layer
            layers_list.pop(idx2)

        # Reconstruct the model with new layer list
        new_layers = nn.ModuleList(layers_list)

        if hasattr(self.model, 'model'):
            if hasattr(self.model.model, 'layers'):
                self.model.model.layers = new_layers

        # CRITICAL: Reassign layer_idx on each layer's self_attn so the
        # KV cache indices match the new layer positions (0, 1, 2, ...)
        for new_idx, layer in enumerate(self.model.model.layers):
            if hasattr(layer, 'self_attn') and hasattr(layer.self_attn, 'layer_idx'):
                layer.self_attn.layer_idx = new_idx

        print(f"✓ Collapsed model now has {len(new_layers)} layers")
        print(f"✓ Reduced from {original_num_layers} to {len(new_layers)} layers")
        print(f"✓ Reassigned layer_idx on all attention layers")

        return self.model

print("✓ LayerCollapser class defined successfully!")

